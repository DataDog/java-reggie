package com.datadoghq.reggie.processor;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;

import com.datadoghq.reggie.runtime.MatchResult;
import com.datadoghq.reggie.runtime.ReggieMatcher;
import java.io.StringWriter;
import java.net.URI;
import java.net.URL;
import java.net.URLClassLoader;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.List;
import java.util.regex.Matcher;
import java.util.regex.Pattern;
import javax.tools.JavaCompiler;
import javax.tools.JavaFileObject;
import javax.tools.SimpleJavaFileObject;
import javax.tools.StandardLocation;
import javax.tools.ToolProvider;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

/**
 * JDK-differential check for non-dotall {@code .}, {@code $} and multiline {@code ^}/{@code $} on
 * {@code @RegexPattern} matchers generated by the annotation processor, on input containing each
 * java.util.regex line terminator and {@code \r\n}.
 */
class DotLineTerminatorProcessorTest {

  private static final String[] PATTERNS = {
    "a.b",
    "(.)(.)",
    "x(.*)",
    "a.+?b",
    "(?m)^.+$",
    "(?m)^(.*)$",
    "(?m)\\d$",
    "(?m)^a*",
    "(?m)^$",
    "(?=.*a)(?=.*b).{3,}",
    "(?m)a[\\r]+?$",
    "(?m)(^a|b)",
    "(?m)^abcdefghijklmnopqrstuvwxyz|b",
    "a.+?$",
    "(\\w)\\1$",
    "(a|b)\\1$"
  };

  private static final String[] TERMINATORS = {"\n", "\r", "\u0085", "\u2028", "\u2029", "\r\n"};

  private static final String[] TEMPLATES = {
    "aTb", "Tab", "abT", "fooTbar", "x1T22", "axbTaxb", "TT", "aT1", "abTTx", "aaTbbT"
  };

  @Test
  void generatedMatchersAgreeWithJdk(@TempDir Path out) throws Exception {
    assertTrue(compile(out), "@RegexPattern provider should compile");
    List<String> inputs = new ArrayList<>(List.of("", "ab", "axb", "x12", "abc"));
    for (String t : TERMINATORS) {
      for (String template : TEMPLATES) {
        inputs.add(template.replace("T", t));
      }
    }
    List<String> mismatches = new ArrayList<>();
    try (URLClassLoader loader =
        new URLClassLoader(new URL[] {out.toUri().toURL()}, getClass().getClassLoader())) {
      Object impl = loader.loadClass("gen.LT$Impl").getDeclaredConstructor().newInstance();
      for (int i = 0; i < PATTERNS.length; i++) {
        ReggieMatcher r = (ReggieMatcher) impl.getClass().getMethod("m" + i).invoke(impl);
        Pattern j = Pattern.compile(PATTERNS[i]);
        for (String in : inputs) {
          String diff;
          try {
            diff = diff(r, j, in);
          } catch (Throwable t) {
            diff = t.toString();
          }
          if (diff != null) {
            mismatches.add("/" + PATTERNS[i] + "/ on \"" + escape(in) + "\": " + diff);
          }
        }
      }
    }
    assertEquals(List.of(), mismatches);
  }

  private static String diff(ReggieMatcher r, Pattern j, String in) {
    Matcher m = j.matcher(in);
    String jdkMatch = m.matches() ? spans(m) : "-";
    MatchResult mr = r.match(in);
    String reggieMatch = mr == null ? "-" : spans(mr);
    if (!jdkMatch.equals(reggieMatch) || r.matches(in) != !jdkMatch.equals("-")) {
      return "match jdk=" + jdkMatch + " reggie=" + reggieMatch + "(" + r.matches(in) + ")";
    }
    for (int start = 0; start <= in.length(); start++) {
      m = j.matcher(in);
      String jdkFrom = m.find(start) ? spans(m) : "-";
      MatchResult fm = r.findMatchFrom(in, start);
      String reggieFrom = fm == null ? "-" : spans(fm);
      int jdkFromStart = jdkFrom.equals("-") ? -1 : m.start();
      int reggieFromStart = r.findFrom(in, start);
      if (!jdkFrom.equals(reggieFrom) || reggieFromStart != jdkFromStart) {
        return "findFrom("
            + start
            + ") jdk="
            + jdkFrom
            + " reggie="
            + reggieFrom
            + "("
            + reggieFromStart
            + ")";
      }
    }
    return null;
  }

  private static String spans(java.util.regex.MatchResult m) {
    StringBuilder sb = new StringBuilder();
    for (int g = 0; g <= m.groupCount(); g++) {
      sb.append('[').append(m.start(g)).append(',').append(m.end(g)).append(')');
    }
    return sb.toString();
  }

  private static String spans(MatchResult m) {
    StringBuilder sb = new StringBuilder();
    for (int g = 0; g <= m.groupCount(); g++) {
      sb.append('[').append(m.start(g)).append(',').append(m.end(g)).append(')');
    }
    return sb.toString();
  }

  private static String escape(String s) {
    return s.replace("\n", "\\n")
        .replace("\r", "\\r")
        .replace("\u0085", "\\u0085")
        .replace("\u2028", "\\u2028")
        .replace("\u2029", "\\u2029");
  }

  private static String provider() {
    StringBuilder sb =
        new StringBuilder(
            "package gen;\n"
                + "import com.datadoghq.reggie.annotations.RegexPattern;\n"
                + "import com.datadoghq.reggie.runtime.ReggieMatcher;\n"
                + "public abstract class LT {\n");
    for (int i = 0; i < PATTERNS.length; i++) {
      String literal = PATTERNS[i].replace("\\", "\\\\").replace("\"", "\\\"");
      sb.append("  @RegexPattern(\"").append(literal).append("\")\n");
      sb.append("  public abstract ReggieMatcher m").append(i).append("();\n");
    }
    return sb.append("}\n").toString();
  }

  private static boolean compile(Path out) throws Exception {
    String code = provider();
    JavaFileObject source =
        new SimpleJavaFileObject(URI.create("string:///gen/LT.java"), JavaFileObject.Kind.SOURCE) {
          @Override
          public CharSequence getCharContent(boolean ignore) {
            return code;
          }
        };
    JavaCompiler javac = ToolProvider.getSystemJavaCompiler();
    var fm = javac.getStandardFileManager(null, null, null);
    fm.setLocation(StandardLocation.CLASS_OUTPUT, List.of(out.toFile()));
    StringWriter sw = new StringWriter();
    boolean ok =
        javac
            .getTask(
                sw,
                fm,
                null,
                Arrays.asList("-classpath", System.getProperty("java.class.path")),
                null,
                List.of(source))
            .call();
    fm.close();
    if (!ok) System.out.println(sw);
    return ok;
  }
}
