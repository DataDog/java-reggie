package com.datadoghq.reggie.processor;

import static org.junit.jupiter.api.Assertions.assertEquals;

import com.datadoghq.reggie.runtime.MatchResult;
import com.datadoghq.reggie.runtime.ReggieMatcher;
import java.util.ArrayList;
import java.util.List;
import java.util.regex.Matcher;
import java.util.regex.Pattern;
import org.junit.jupiter.api.Test;

/**
 * JDK-differential check of {@code findMatchFrom} group spans on annotation-processor generated
 * matchers whose patterns read text around the match (lookbehind before the match start, lookahead
 * past the match end, anchors).
 */
class FindMatchFromContextProcessorTest {

  private static final String[] PATTERNS = {
    "(?<=a)(x{1,25})",
    "(?<=a)(x{1,25})y",
    "(?<!a)(x{1,25})",
    "(x{1,25})(?=b)",
    "(?<=a)(x)(y)",
    "(?<=a)(xy|z)",
    "(?m)^(x{1,25})",
    "(x{1,25})$",
    "(?<=a)(x+)",
    "(?:(a)\\b|(a))x?",
    "(?:\\b(a)|(a))x{1,25}",
    "(a)(?:\\b|(b))",
  };

  private static final String[] INPUTS = {
    "ax", "axx", "bx", "bxax", "xb", "xxbx", "axy", "baxy", "az", "x\nxx", "xx\nx", "ax\n", "axxa",
    "bax", "baxx", "xax", "a b", "ab", "aby", "xy", "b ax"
  };

  @Test
  void findMatchFromAgreesWithJdk() throws Exception {
    List<String> mismatches = new ArrayList<>();
    for (int i = 0; i < PATTERNS.length; i++) {
      ReggieMatcherBytecodeGenerator gen =
          new ReggieMatcherBytecodeGenerator("test.generated", "FmC" + i, PATTERNS[i]);
      byte[] bytecode = gen.generate();
      ReggieMatcher r =
          (ReggieMatcher)
              new TestClassLoader()
                  .defineClass("test.generated.FmC" + i, bytecode)
                  .getDeclaredConstructor()
                  .newInstance();
      Pattern j = Pattern.compile(PATTERNS[i]);
      for (String in : INPUTS) {
        for (int from = 0; from <= in.length(); from++) {
          Matcher m = j.matcher(in);
          String expected = m.find(from) ? spans(m) : "-";
          MatchResult mr = r.findMatchFrom(in, from);
          String actual = mr == null ? "-" : spans(mr);
          if (!actual.equals(expected)) {
            mismatches.add(
                "/"
                    + PATTERNS[i]
                    + "/ ("
                    + gen.resolvedStrategy()
                    + ") on \""
                    + in.replace("\n", "\\n")
                    + "\" from "
                    + from
                    + ": jdk="
                    + expected
                    + " reggie="
                    + actual);
          }
        }
      }
    }
    assertEquals(List.of(), mismatches);
  }

  private static String spans(java.util.regex.MatchResult m) {
    StringBuilder sb = new StringBuilder();
    for (int g = 0; g <= m.groupCount(); g++) {
      sb.append('[').append(m.start(g)).append(',').append(m.end(g)).append(')');
    }
    return sb.toString();
  }

  private static String spans(MatchResult m) {
    StringBuilder sb = new StringBuilder();
    for (int g = 0; g <= m.groupCount(); g++) {
      sb.append('[').append(m.start(g)).append(',').append(m.end(g)).append(')');
    }
    return sb.toString();
  }

  /** Custom ClassLoader for loading generated bytecode in tests. */
  private static class TestClassLoader extends ClassLoader {
    Class<?> defineClass(String name, byte[] bytecode) {
      return defineClass(name, bytecode, 0, bytecode.length);
    }
  }
}
