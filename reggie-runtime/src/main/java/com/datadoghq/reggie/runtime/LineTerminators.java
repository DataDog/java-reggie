package com.datadoghq.reggie.runtime;

/**
 * java.util.regex line-terminator rules (non-UNIX_LINES mode). The terminators are {@code \n},
 * {@code \r}, NEL (U+0085), LS (U+2028) and PS (U+2029); {@code \r\n} counts as one terminator.
 *
 * <p>Called by runtime matchers and, via {@code INVOKESTATIC}, by generated bytecode.
 */
public final class LineTerminators {

  private LineTerminators() {}

  /** True if {@code c} is one of the five line terminators. */
  public static boolean isLineTerminator(char c) {
    return c == '\n' || c == '\r' || c == '\u0085' || (c | 1) == '\u2029';
  }

  /**
   * Multiline {@code ^} at {@code pos}. Same rules as java.util.regex: never at {@code end}; always
   * at {@code start}; otherwise after a line terminator, but not between {@code \r} and {@code \n}.
   *
   * @param start the start bound of the input (0 unless a region is set)
   * @param end the end bound of the input (its length unless a region is set)
   */
  public static boolean isMultilineStart(CharSequence input, int pos, int start, int end) {
    if (pos == end) {
      return false;
    }
    if (pos > start) {
      char prev = input.charAt(pos - 1);
      if (!isLineTerminator(prev)) {
        return false;
      }
      return prev != '\r' || input.charAt(pos) != '\n';
    }
    return true;
  }

  /**
   * Multiline {@code $} at {@code pos}. Same rules as java.util.regex: always at {@code end};
   * otherwise before a line terminator, but not between {@code \r} and {@code \n}.
   *
   * @param end the end bound of the input (its length unless a region is set)
   */
  public static boolean isMultilineEnd(CharSequence input, int pos, int end) {
    if (pos >= end) {
      return true;
    }
    char c = input.charAt(pos);
    if (c == '\n') {
      return pos == 0 || input.charAt(pos - 1) != '\r';
    }
    return c == '\r' || c == '\u0085' || (c | 1) == '\u2029';
  }

  /**
   * Non-multiline {@code $} (and {@code \Z}) at {@code pos}. Same rules as java.util.regex: at
   * {@code end}; before a final line terminator at {@code end - 1} (not the {@code \n} of a {@code
   * \r\n}); or before a final {@code \r\n} at {@code end - 2}.
   *
   * @param end the end bound of the input (its length unless a region is set)
   */
  public static boolean isEnd(CharSequence input, int pos, int end) {
    if (pos >= end) {
      return true;
    }
    if (pos == end - 1) {
      return isMultilineEnd(input, pos, end);
    }
    return pos == end - 2 && input.charAt(pos) == '\r' && input.charAt(pos + 1) == '\n';
  }
}
